export const GLYPH_HEIGHT = 7;

/** Normalisiert Text auf den Zeichenvorrat der Schrift. */
export function normalizePixelText(text: string): string {
  return text
    .toUpperCase()
    .replace(/ß/g, 'SS')
    .replace(/[ÉÈÊ]/g, 'E')
    .replace(/[ÀÂ]/g, 'A');
}

export interface PixelRun {
  x: number;
  y: number;
  w: number;
}

/** Zerlegt Text in waagrechte Pixel-Läufe. Gibt Läufe und Gesamtbreite zurück. */
export function layoutPixelText(text: string): { runs: PixelRun[]; width: number } {
  const runs: PixelRun[] = [];
  let x = 0;
  const chars = [...normalizePixelText(text)];
  chars.forEach((ch, i) => {
    const g = G[ch] ?? G['?'];
    const gw = g[0].length;
    for (let y = 0; y < GLYPH_HEIGHT; y++) {
      const row = g[y];
      let start = -1;
      for (let c = 0; c <= gw; c++) {
        const on = row[c] === '#';
        if (on && start < 0) start = c;
        if (!on && start >= 0) {
          runs.push({ x: x + start, y, w: c - start });
          start = -1;
        }
      }
    }
    x += gw + (i < chars.length - 1 ? 1 : 0);
  });
  return { runs, width: x };
}
